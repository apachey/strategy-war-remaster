/** Letters that look the same in Latin and Cyrillic, and other characters that share a glyph. */
const SAME: Record<string, string> = {
  А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X', І: 'I',
  а: 'a', е: 'e', о: 'o', р: 'p', с: 'c', у: 'y', х: 'x', і: 'i',
  ʼ: "'", '’': "'", '‘': "'", '“': '"', '”': '"', '−': '-', $: '◆', '⏵': '▶', '✗': '✕',
};
// Ё ё are not Ukrainian but appear in names now and then.
GLYPHS['Ё'] = '9 .#.#./...../#####/#..../#..../####./#..../#..../#####';
GLYPHS['ё'] = '7 .#.#./...../.###./#...#/#####/#..../.###.';

export interface Bitmap {
  /** Height above the baseline of the first row. */
  top: number;
  rows: string[];
  width: number;
}

/** A character's bitmap, regular or bold (thickened one pixel to the right), or null when the font lacks it. */
export function glyph(ch: string, bold = false): Bitmap | null {
  const spec = GLYPHS[ch] ?? GLYPHS[SAME[ch] ?? ''];
  if (!spec) return null;
  const [top, body] = spec.split(' ') as [string, string];
  let rows = body.split('/');
  // Bold: every stroke one pixel wider to the right, except where that would close a one-pixel gap (Ш, м, ж).
  if (bold) rows = rows.map((r) => [...`${r}.`].map((c, i) => (c === '#' || (r[i - 1] === '#' && r[i + 1] !== '#') ? '#' : '.')).join(''));
  return { top: Number(top), rows, width: Math.max(...rows.map((r) => r.length)) };
}

/** Every character the font draws. */
export const CHARSET = [...new Set([...Object.keys(GLYPHS), ...Object.keys(SAME)])];

/** The font as a TrueType file: every lit run of pixels in a row is one rectangle. */
export function buildFont(bold: boolean): ArrayBuffer {
  const glyphs = [
    new opentype.Glyph({ name: '.notdef', unicode: 0, advanceWidth: 4 * UNIT, path: new opentype.Path() }),
    new opentype.Glyph({ name: 'space', unicode: 32, advanceWidth: 3 * UNIT, path: new opentype.Path() }),
    new opentype.Glyph({ name: 'nbsp', unicode: 0xa0, advanceWidth: 3 * UNIT, path: new opentype.Path() }),
  ];
  for (const ch of CHARSET) {
    const g = glyph(ch, bold)!;
    const path = new opentype.Path();
    g.rows.forEach((row, r) => {
      const y1 = (g.top - r) * UNIT;
      const y0 = y1 - UNIT;
      for (let x = 0; x < row.length; ) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        let end = x;
        while (row[end] === '#') end++;
        // Clockwise outer contours, as TrueType expects.
        path.moveTo(x * UNIT, y0);
        path.lineTo(x * UNIT, y1);
        path.lineTo(end * UNIT, y1);
        path.lineTo(end * UNIT, y0);
        path.close();
        x = end;
      }
    });
    glyphs.push(new opentype.Glyph({ name: `u${ch.codePointAt(0)!.toString(16)}`, unicode: ch.codePointAt(0)!, advanceWidth: (g.width + 1) * UNIT, path }));
  }
  const font = new opentype.Font({
    familyName: 'Shardfall',
    styleName: bold ? 'Bold' : 'Regular',
    unitsPerEm: EM,
    ascender: ASCENT * UNIT,
    descender: -DESCENT * UNIT,
    glyphs,
  });
  return font.toArrayBuffer();
}

let loaded: Promise<void> | null = null;

/** Builds both cuts and registers them as the `Shardfall` family (weights 400 and 700). */
export function loadFonts(): Promise<void> {
  loaded ??= (async () => {
    for (const bold of [false, true]) {
      const face = new FontFace('Shardfall', buildFont(bold), { weight: bold ? '700' : '400' });
      document.fonts.add(await face.load());
    }
  })();
  return loaded;
}
